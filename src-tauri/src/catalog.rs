//! Kuratierte Modellliste. Spracherkennung, VAD und Diarisierung laufen über
//! transcribe-cpp (GGUF-Dateien aus den handy-computer-Repos auf Hugging Face),
//! Enhance über llama-server mit Gemma 4.

use serde::Serialize;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ModelKind {
    Asr,
    Vad,
    Diarize,
    Llm,
}

#[derive(Clone, Debug, Serialize)]
pub struct ModelInfo {
    pub id: &'static str,
    pub name: &'static str,
    pub description_de: &'static str,
    pub description_en: &'static str,
    pub kind: ModelKind,
    pub family: &'static str,
    pub repo: &'static str,
    pub revision: &'static str,
    pub filename: &'static str,
    pub size: u64,
    pub sha256: &'static str,
    /// Sprachcodes; leer = nicht relevant.
    pub languages: &'static [&'static str],
    /// 1–5, höher = schneller.
    pub speed: u8,
    /// 1–5, höher = genauer.
    pub accuracy: u8,
    pub recommended: bool,
}

impl ModelInfo {
    pub fn url(&self) -> String {
        format!(
            "https://huggingface.co/{}/resolve/{}/{}",
            self.repo, self.revision, self.filename
        )
    }
}

