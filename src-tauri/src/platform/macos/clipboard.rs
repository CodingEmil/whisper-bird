//! Zwischenablage über NSPasteboard: Text setzen/lesen und den kompletten Inhalt
//! sichern und wiederherstellen (alle Einträge mit allen Typen).

use crate::platform::clipboard::Snapshot;
use objc2::rc::autoreleasepool;
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{NSPasteboard, NSPasteboardItem, NSPasteboardTypeString, NSPasteboardWriting};
use objc2_foundation::{NSArray, NSData, NSString};

/// Konvention von nspasteboard.org: Zwischenablage-Manager (Maccy, Raycast, Alfred …)
/// übernehmen so markierte Inhalte nicht in ihren Verlauf.
const TRANSIENT_TYPES: [&str; 2] = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];

fn board() -> objc2::rc::Retained<NSPasteboard> {
    NSPasteboard::generalPasteboard()
}

pub fn sequence() -> u32 {
    board().changeCount() as u32
}

pub fn snapshot() -> Snapshot {
    autoreleasepool(|_| {
        let mut snap = Snapshot::default();
        let Some(items) = board().pasteboardItems() else { return snap };
        for item in items.iter() {
            let mut entry = Vec::new();
            for kind in item.types().iter() {
                if let Some(data) = item.dataForType(&kind) {
                    entry.push((kind.to_string(), data.to_vec()));
                }
            }
            if !entry.is_empty() {
                snap.items.push(entry);
            }
        }
        snap
    })
}

pub fn restore(snap: &Snapshot) {
    autoreleasepool(|_| {
        let pb = board();
        pb.clearContents();
        let items: Vec<_> = snap
            .items
            .iter()
            .map(|entry| {
                let item = NSPasteboardItem::new();
                for (kind, data) in entry {
                    item.setData_forType(&NSData::with_bytes(data), &NSString::from_str(kind));
                }
                ProtocolObject::<dyn NSPasteboardWriting>::from_retained(item)
            })
            .collect();
        if !items.is_empty() {
            pb.writeObjects(&NSArray::from_retained_slice(&items));
        }
    })
}

/// Setzt Text. `transient`: von Zwischenablage-Managern nicht mitschneiden lassen.
pub fn set_text(text: &str, transient: bool) -> anyhow::Result<()> {
    autoreleasepool(|_| {
        let pb = board();
        pb.clearContents();
        let item = NSPasteboardItem::new();
        let kind = unsafe { NSPasteboardTypeString };
        if !item.setString_forType(&NSString::from_str(text), kind) {
            anyhow::bail!("Text konnte nicht in die Zwischenablage gelegt werden");
        }
        if transient {
            for marker in TRANSIENT_TYPES {
                item.setData_forType(&NSData::new(), &NSString::from_str(marker));
            }
        }
        let items = [ProtocolObject::<dyn NSPasteboardWriting>::from_retained(item)];
        if !pb.writeObjects(&NSArray::from_retained_slice(&items)) {
            anyhow::bail!("Zwischenablage hat den Text abgelehnt");
        }
        Ok(())
    })
}

pub fn get_text() -> Option<String> {
    autoreleasepool(|_| {
        let kind = unsafe { NSPasteboardTypeString };
        board().stringForType(kind).map(|s| s.to_string())
    })
}

pub fn clear() {
    board().clearContents();
}
