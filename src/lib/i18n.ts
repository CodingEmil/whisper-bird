export type TKey = Key;

export function translate(lang: string, key: TKey, vars?: Record<string, string | number>): string {
  let s = (lang === "de" ? de : en)[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  }
  return s;
}

